import json

from openai import AsyncOpenAI

from config import OPENAI_API_KEY, OPENAI_MODEL


client = AsyncOpenAI(api_key=OPENAI_API_KEY)


FACT_CHECK_PROMPT = """
Ти — фактчекер українського Telegram-бота AntiFakeUA.

Твоє завдання — перевірити надісланий користувачем текст: новину, заяву, пересланий допис або окреме твердження.
Відповідай українською мовою, нейтрально й обережно. Не підтримуй жодну політичну сторону. Оцінюй тільки зміст твердження, докази та контекст.

Обов'язкові принципи:
1. Не вигадуй фактів, дат, цитат, джерел або посилань.
2. Використовуй web search для перевірки актуальної інформації.
3. Відрізняй факт від думки, прогнозу, емоційної оцінки або припущення.
4. Якщо даних замало — обирай verdict "Недостатньо даних", а не роби категоричний висновок.
5. Якщо повідомлення частково правдиве, але подане так, що вводить в оману, обирай "Маніпуляція".
6. Якщо стару подію, фото, заяву або новину подають як нову — це зазвичай "Маніпуляція" або "Інше", залежно від контексту.
7. Якщо текст не містить перевірюваного фактичного твердження, обирай "Недостатньо даних" і коротко поясни чому.
8. Не називай джерело або людину брехливою загалом. Оцінюй лише конкретне повідомлення.

Вердикти:
- "Правда" — основне твердження підтверджується надійними джерелами.
- "Фейк" — основне твердження суперечить надійним джерелам або є вигаданим.
- "Маніпуляція" — є правда або частина правди, але подача перекручує контекст, перебільшує, приховує важливі деталі або емоційно тисне.
- "Недостатньо даних" — немає достатніх доказів для надійного висновку або твердження неможливо перевірити.
- "Інше" — випадки, які не підходять під попередні категорії, наприклад сатиру, жарт, особисту думку або неінформаційний текст.

Поле headline:
- обов'язково заповни одним коротким реченням без крапки в кінці;
- 6–14 слів; це жирний заголовок, який людина має зрозуміти без читання пояснення;
- прямо скажи, що саме підтверджено, спростовано або викривлено;
- не використовуй загальні фрази на кшталт "Інформація підтверджується" без суті;
- приклади: "Після підриву Каховської ГЕС Великий Луг справді відновлюється"; "Відео не показує заявлений ракетний удар".

Поле summary:
- 2–4 короткі речення;
- починай одразу з фактів і доказів, а не з опису процесу перевірки;
- не починай словами "Перевіряється твердження", "Було перевірено твердження", "У дописі стверджується" або подібними канцелярськими конструкціями;
- не повторюй headline слово в слово;
- якщо є невизначеність, прямо вкажи її;
- не пиши довгу статтю;
- не додавай посилання, домени в квадратних дужках або сирі URL.

Поле blocks:
- використовуй рідко: тільки якщо є важливе уточнення, яке не вмістилося в summary;
- максимум 1 блок;
- не дублюй summary;
- пиши як продовження пояснення, без заголовків типу "Деталі:" або "Уточнення:";
- не додавай посилання або сирі URL.

Поле sources:
- 0–5 джерел;
- тільки реальні URL;
- пріоритет: офіційні джерела, першоджерела, міжнародні агентства, авторитетні медіа;
- не додавай джерело, якщо воно не підтверджує зміст відповіді.
"""


FACT_CHECK_SCHEMA = {
    "type": "object",
    "properties": {
        "verdict": {
            "type": "string",
            "enum": [
                "Правда",
                "Фейк",
                "Маніпуляція",
                "Недостатньо даних",
                "Інше",
            ],
        },
        "headline": {
            "type": "string",
        },
        "summary": {
            "type": "string",
        },
        "blocks": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "type": {
                        "type": "string",
                        "enum": [
                            "Деталі",
                            "Уточнення",
                            "Застереження",
                        ],
                    },
                    "text": {
                        "type": "string",
                    },
                },
                "required": ["type", "text"],
                "additionalProperties": False,
            },
        },
        "sources": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "title": {
                        "type": "string",
                    },
                    "url": {
                        "type": "string",
                    },
                },
                "required": ["title", "url"],
                "additionalProperties": False,
            },
        },
    },
    "required": ["verdict", "headline", "summary", "blocks", "sources"],
    "additionalProperties": False,
}


async def analyze_text(text: str) -> dict:
    if not OPENAI_API_KEY:
        return build_error_result(
            "OPENAI_API_KEY не заданий у .env. Адміністратор має додати API-ключ."
        )

    try:
        response = await client.responses.create(
            model=OPENAI_MODEL,
            tools=[
                {
                    "type": "web_search_preview",
                }
            ],
            input=[
                {
                    "role": "developer",
                    "content": FACT_CHECK_PROMPT,
                },
                {
                    "role": "user",
                    "content": text,
                },
            ],
            text={
                "format": {
                    "type": "json_schema",
                    "name": "fact_check_result",
                    "strict": True,
                    "schema": FACT_CHECK_SCHEMA,
                }
            },
        )

        return json.loads(response.output_text)

    except Exception as error:
        print(f"GPT ERROR: {error}")

        return build_error_result(
            "Під час аналізу виникла технічна помилка. Спробуй повторити запит пізніше."
        )


def build_error_result(message: str) -> dict:
    return {
        "verdict": "Недостатньо даних",
        "headline": "Перевірку не завершено через технічну помилку",
        "summary": message,
        "blocks": [],
        "sources": [],
    }
