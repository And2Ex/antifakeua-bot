async def analyze_text(text: str) -> dict:
    if not OPENAI_API_KEY:
        return build_error_result(
            "OPENAI_API_KEY не заданий у .env. Адміністратор має додати API-ключ."
        )

    try:
        response = await client.responses.create(
            model=OPENAI_MODEL,
            tools=[{"type": "web_search"}],
            tool_choice="required",
            input=[
                {"role": "developer", "content": FACT_CHECK_PROMPT},
                {"role": "user", "content": text},
            ],
            text={
                "format": {
                    "type": "json_schema",
                    "name": "fact_check_result",
                    "strict": True,
                    "schema": FACT_CHECK_SCHEMA,
                }
            },
        )

        return enforce_verdict_policy(json.loads(response.output_text))

    except Exception as error:
        print(f"GPT ERROR: {error}")

        return build_error_result(
            "Під час аналізу виникла технічна помилка. Спробуй повторити запит пізніше."
        )


def enforce_verdict_policy(result: dict) -> dict:
    """Keep the technical family consistent with the visible controlled verdict."""
    verdict = str(result.get("verdict", "")).strip()
    family_by_verdict = {
        "Правда": "true",
        "Маніпуляція": "mixed",
        "Частково неправда": "false",
        "Неправда": "false",
        "Непідтверджено": "uncertain",
        "Не підлягає перевірці": "other",
    }

    result["analysis_revision"] = CURRENT_ANALYSIS_REVISION
    result["verdict_family"] = family_by_verdict.get(verdict, "uncertain")

    if verdict == "Правда":
        result["short_reason"] = ""

    return result


def build_error_result(message: str) -> dict:
    return {
        "analysis_revision": CURRENT_ANALYSIS_REVISION,
        "content_type": "non_checkable",
        "public_mark_allowed": False,
        "verdict_family": "uncertain",
        "verdict": "Непідтверджено",
        "short_reason": "технічна помилка",
        "queue_title": "Перевірка тимчасово недоступна",
        "summary": message,
        "blocks": [],
        "sources": [],
    }
